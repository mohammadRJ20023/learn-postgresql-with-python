------------------------------------------------
-- مشاهده وضعیت فعلی
------------------------------------------------

SELECT * FROM users;

------------------------------------------------
-- تغییر نام کاربر با id = 1
------------------------------------------------

UPDATE users
SET first_name = 'Mohammad'
WHERE id = 1;

------------------------------------------------
-- تغییر چند ستون همزمان
------------------------------------------------

UPDATE users
SET
    last_name = 'Hosseini',
    phone = '09120000000'
WHERE id = 2;

------------------------------------------------
-- غیرفعال کردن کاربر
------------------------------------------------

UPDATE users
SET is_active = FALSE
WHERE id = 3;

------------------------------------------------
-- بررسی نتیجه
------------------------------------------------

SELECT * FROM users;

------------------------------------------------
-- حذف کاربر با id = 3
------------------------------------------------

DELETE FROM users
WHERE id = 3;

------------------------------------------------
-- بررسی نتیجه
------------------------------------------------

SELECT * FROM users;